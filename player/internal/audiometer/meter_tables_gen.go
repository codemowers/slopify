// Build-time floating-point math only; the meter uses integer comparisons.
package main

import (
	"fmt"
	"math"
)

func main() {
	fmt.Println("// Code generated by meter_tables_gen.go; DO NOT EDIT.\n\npackage audiometer\n")
	fmt.Println("// Minimum S32 magnitude rounding to each dBFS step (0 through -126).")
	fmt.Println("var dbThresholds = [...]uint32{")
	for attenuation := 0; attenuation < 127; attenuation++ {
		fmt.Printf("%d,\n", uint32(math.Ceil((1<<31)*math.Pow(10, -(float64(attenuation)+.5)/20))))
	}
	fmt.Println("}")
}
